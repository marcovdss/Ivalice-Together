"""Generate the data table used by the in-game Lua configuration page.

The Lua page must not keep a hand-copied version of these defaults.  Run this
after changing controller defaults, theme aliases or party labels; the test
suite fails while the generated file is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path


DEVELOPMENT = Path(__file__).resolve().parents[1]
SOURCE = DEVELOPMENT / "source"
TARGET = DEVELOPMENT / "lua/scripts/IvaliceTogetherMenu/defaults.lua"


def _lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    sys.path.insert(0, str(SOURCE))
    import controller_bindings
    import menu_themes

    defaults = controller_bindings.default_config()["players"]
    lines = [
        "-- Generated by ferramentas/gerar_padroes_menu_lua.py. Do not edit.",
        "return {",
        "  padControls = {",
    ]
    for player in controller_bindings.PLAYER_IDS:
        lines.append(f"    {player} = {{")
        for action, bindings in defaults[player].items():
            control = next(
                (b["control"] for b in bindings if b.get("device") == "xinput"),
                None,
            )
            if control is not None:
                lines.append(f"      [{_lua_string(action)}] = {_lua_string(control)},")
        lines.append("    },")
    lines.append("  },")
    lines.append("  themeAliases = {")
    for alias, name in sorted(menu_themes.ALIASES.items()):
        lines.append(f"    [{_lua_string(alias)}] = {_lua_string(name)},")
    lines.append("  },")
    lines.append("  partyMemberIds = {")
    for label, member_id in sorted(menu_themes.PARTY_MEMBER_IDS.items()):
        lines.append(f"    [{_lua_string(label)}] = {int(member_id)},")
    lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
